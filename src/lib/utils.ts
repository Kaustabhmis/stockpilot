import { clsx, type ClassValue } from "clsx"
import { twMerge } from "tailwind-merge"

export function cn(...inputs: ClassValue[]) {
  return twMerge(clsx(inputs))
}

export const formatCurrency = (value: number) => new Intl.NumberFormat('en-IN', { style: 'currency', currency: 'INR', minimumFractionDigits: 0, maximumFractionDigits: 0 }).format(value || 0);

export const formatDate = (timestamp?: { seconds: number }) => timestamp ? new Date(timestamp.seconds * 1000).toLocaleDateString('en-CA') : 'N/A';
